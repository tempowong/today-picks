function preMatch(value: number): Extract<VerifiedOdds, { status: "published"; isPreMatch: true }> {
  return {
    status: "published",
    value,
    isPreMatch: true,
    source: "bet.hkjc.com",
    verified: true,
  };
}

function inPlay(
  value: number,
  at: string,
): Extract<VerifiedOdds, { status: "published"; isPreMatch: false }> {
  return {
    status: "published",
    value,
    isPreMatch: false,
    label: "即場",
    inPlayUpdatedAtHkt: at,
    source: "bet.hkjc.com",
    verified: true,
  };
}

function steps(bodies: [string, string, string, string, string]): SeedMatch["view"]["steps"] {
  return bodies.map((body, index) => ({
    n: String(index + 1),
    title: STEP_TITLES[index] ?? "",
    body,
  }));
}

function match(row: SeedMatch): SeedMatch {
  return row;
}

